"""Промпты для репаратора (повторная генерация по фидбэку аудитора).

Retry-промпт строится из:
- той же системной части, что у генератора (правила безопасности и т.д.);
- исходной задачи пользователя;
- предыдущего SQL;
- структурированного фидбэка аудитора (найденные уязвимости + рекомендации);
- явной инструкции: сначала исправить критические проблемы, не ломая
  уже корректные части.
"""

from __future__ import annotations

from app.schemas.sql import AuditResult


# Системная часть переиспользует правила из генератора, но добавляет
# инструкцию про режим исправления.
REPAIR_SYSTEM_PROMPT = """Ты -- эксперт по PostgreSQL в режиме ИСПРАВЛЕНИЯ SQL-запроса.

Тебе дан запрос, который не прошёл аудит безопасности. Твоя задача -- исправить
выявленные проблемы и вернуть улучшенный SQL.

## Целевая СУБД
PostgreSQL (совместимость с версиями 12+, без сторонних расширений).

## Правила безопасности (СТРОГО соблюдать)

1. Параметризация: пользовательские значения -- параметры ($1, $2, ...), не конкатенация.
2. WHERE обязателен для UPDATE/DELETE.
3. Никаких SELECT * -- перечисляй колонки явно.
4. Чувствительные поля (пометка [!] в схеме) не выдавать без явного требования.
5. LIMIT для запросов, возвращающих много строк.
6. Никакого динамического SQL (EXECUTE, format() с вводом).

## Как исправлять

- Сначала устрани КРИТИЧЕСКИЕ замечания (высокий risk_score), затем остальные.
- Не вноси изменений, не связанных с замечаниями аудитора. Не ломай уже
  корректные части запроса.
- Если замечание касается производительности -- оптимизируй, сохраняя корректность.

## Формат ответа

Верни ТОЛЬКО исправленный SQL-запрос. Без преамбулы, без объяснений, без
markdown-обёрток ```sql. Чистый SQL.

## Схема базы данных (релевантные таблицы)

{schema}
"""


def _format_audit_feedback(audit: AuditResult) -> str:
    """Превращает AuditResult в читаемый для модели блок замечаний."""
    lines = [
        f"Итоговая оценка риска: {audit.overall_risk}/10.",
        f"Вердикт аудитора: {audit.summary}",
        "",
        "Найденные проблемы:",
    ]
    if not audit.findings:
        lines.append("- (конкретные находки не указаны)")
    else:
        # Сортируем по убыванию риска -- критическое первым
        findings = sorted(audit.findings, key=lambda f: f.risk_score, reverse=True)
        for i, f in enumerate(findings, 1):
            block = [
                f"{i}. [{f.vulnerability_class.value}] риск {f.risk_score}/10",
                f"   Проблема: {f.explanation}",
            ]
            if f.suggested_fix:
                block.append(f"   Как исправить: {f.suggested_fix}")
            lines.append("\n".join(block))
    return "\n".join(lines)


def build_repair_system_prompt(schema_text: str) -> str:
    """Системный промпт для исправления."""
    return REPAIR_SYSTEM_PROMPT.format(schema=schema_text)


def build_repair_user_prompt(
    *,
    task_description: str,
    previous_sql: str,
    audit: AuditResult,
    iteration: int,
) -> str:
    """Пользовательская часть retry-промпта: задача + прошлый SQL + фидбэк."""
    feedback = _format_audit_feedback(audit)
    return f"""## Исходная задача
{task_description.strip()}

## Предыдущий SQL (итерация {iteration - 1})
{previous_sql.strip()}

## Замечания аудитора, которые нужно исправить
{feedback}

## Задание
Исправь SQL согласно замечаниям выше. Верни только исправленный SQL."""